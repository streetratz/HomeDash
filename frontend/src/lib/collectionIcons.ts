const ICON_SET: ReadonlySet<string> = new Set(COLLECTION_ICONS);

export function isCollectionIcon(value: unknown): value is CollectionIcon {
  return typeof value === 'string' && ICON_SET.has(value);
}

/**
 * Resolve an icon name to its bundled lucide component, falling back to the
 * default bin icon for unknown or legacy values so rendering never fails.
 */
export function collectionIconComponent(name: string | null | undefined): LucideIcon {
  return isCollectionIcon(name) ? ICON_COMPONENTS[name] : ICON_COMPONENTS[DEFAULT_COLLECTION_ICON];
}
